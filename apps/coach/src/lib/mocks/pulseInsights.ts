import type { AcademyPulseInsight, PulseInsightChartSet } from '@openmat/shared';

function charts(
  lineTitle: string,
  barsTitle: string,
  sets: {
    range: '7d' | '30d' | '90d';
    summaryValue: string;
    summaryHelper: string;
    trendLabel: string;
    line: Array<[string, number]>;
    bars: Array<[string, number]>;
  }[],
): Record<'7d' | '30d' | '90d', PulseInsightChartSet> {
  const result = {} as Record<'7d' | '30d' | '90d', PulseInsightChartSet>;
  for (const set of sets) {
    result[set.range] = {
      summaryValue: set.summaryValue,
      summaryHelper: set.summaryHelper,
      trendLabel: set.trendLabel,
      lineTitle,
      barsTitle,
      line: set.line.map(([label, value]) => ({ label, value })),
      bars: set.bars.map(([label, value]) => ({ label, value })),
    };
  }
  return result;
}

